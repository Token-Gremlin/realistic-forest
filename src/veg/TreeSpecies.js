/** Species mix by ecology. Each entry: [speciesKey, scoring function]. */
export const SPECIES_RULES = [
  ['beech', (e) => 0.35 + e.canopy * 1.5 + e.moisture * 0.5 - e.rock * 1.2 - e.slope * 0.8],
  ['oak', (e) => 0.55 + e.canopy * 0.9 + (1 - e.moisture) * 0.4 - e.rock * 0.7 - e.slope * 0.5],
  ['birch', (e) => 0.25 + (1 - e.canopy) * 1.2 + e.moisture * 0.6 - e.rock * 0.4],
  ['pine', (e) => 0.20 + e.rock * 1.5 + e.slope * 1.0 + (1 - e.moisture) * 0.7],
  ['fir', (e) => 0.15 + e.canopy * 0.8 + e.moisture * 0.7 + e.slope * 0.5 - e.rock * 0.2],
  ['hazel', (e) => 0.30 + (1 - e.canopy) * 0.9 + e.moisture * 0.7 - e.rock * 0.5],
  ['sapling', (e) => 0.20 + (1 - e.canopy) * 1.8 + e.litter * 0.4 - e.rock * 0.6],
  ['snag', (e) => 0.08 + e.canopy * 0.35 + e.moisture * 0.2],
];

export function pickSpecies(eco, rnd) {
  let total = 0;
  const scores = [];
  for (const [key, fn] of SPECIES_RULES) {
    const s = Math.max(0.001, fn(eco));
    scores.push([key, s]);
    total += s;
  }
  let r = rnd * total;
  for (const [key, s] of scores) {
    r -= s;
    if (r <= 0) return key;
  }
  return scores[0][0];
}
